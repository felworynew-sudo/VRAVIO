/// Точка входа десктопной оболочки.
///
/// Здесь намеренно пусто. Весь редактор — тот же самый веб-код, который
/// собирается `vite build`; десктоп не добавляет к нему ни одной команды и
/// не подменяет ни одного порта. Как только оболочка начнёт что-то знать о
/// документах, появится вторая реализация того же поведения, и она разойдётся
/// с первой — ровно та ошибка, которую весь план вычищал одиннадцать этапов.
///
/// Настоящая разница между вебом и десктопом живёт в портах платформы ядра
/// (файлы, шрифты, буфер обмена). Когда десктопные их варианты понадобятся,
/// они появятся там, а не здесь.
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
